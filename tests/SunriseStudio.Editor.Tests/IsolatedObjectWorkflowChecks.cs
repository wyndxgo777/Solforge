using System.Diagnostics;
using System.Numerics;
using SunriseStudio.Authoring;
using SunriseStudio.Editor;
using SunriseStudio.Packages;
using SunriseStudio.Scene;

/** Checks that isolated object assets are published by the workspace with overlay metadata and do not leak into authored browser rows. */
internal static class IsolatedObjectWorkflowChecks
{
    /** Entry point: runs every check in this class and throws on the first failure. */
    internal static void Run(string root)
    {
        string install = Path.Combine(root, "isolated-object-install");
        StaticIsolationFixture.Write(install);
        using var workspace = new StudioWorkspace { CacheOptions = new() { Enabled = false } };
        workspace.OpenInstallation(install); Wait(workspace);
        workspace.CreateProject(Path.Combine(root, "isolated-object-project"), "Isolated tree"); Wait(workspace);
        var catalog = workspace.Catalog!;
        var project = workspace.Project!;
        var edit = StaticIsolationFixture.Edit(catalog, StaticIsolationFixture.Table, 1, 3);
        workspace.ApplyObjectEdit(edit); Wait(workspace);
        Check(workspace.ObjectEditError.Length == 0 && workspace.CompiledObjects.GeneratedAssets.Count == 4,
            "Workspace did not publish isolated object assets.");
        var generatedTags = workspace.CompiledObjects.GeneratedAssets.Select(asset => asset.TagHash).ToHashSet();
        Check(catalog.GetOverlayEntries().Count(entry => entry.Generated) == 4 && project.AddedAssets.Count == 0,
            "Generated bytes entered authored assets or lost overlay metadata.");
        Check(catalog.TryGetEntry(StaticIsolationFixture.Container, out var container)
            && container.Size == catalog.Read(StaticIsolationFixture.Container).Length,
            "Compiled container metadata retained the original size.");
        Check(workspace.Assets.All(row => !generatedTags.Contains(row.Entry.TagHash)),
            "Private generated assets leaked into authored browser rows.");
        var selected = Preview(catalog, workspace);
        var world = workspace.World!;
        var target = SceneEdits.Describe(catalog, selected).Target;
        Check(target == edit.Target, "Scene inspection changed the original editable target.");
        var next = SceneEdits.CreateTransformEdit(catalog, selected, selected.Transform.Translation, null, 4)!;
        workspace.ApplyObjectEdit(next); Wait(workspace);
        Check(project.ObjectEdits.Single().Target == edit.Target && project.ObjectEdits.Single().Scale == 4,
            "Editing the replacement created a second target.");
        Check(workspace.LastWorldRefresh is { Incremental: true } && ReferenceEquals(workspace.World, world)
            && selected.Transform.M11 == 4 && world.Scene.Instances.Count == 3,
            "A repeated isolated transform rebuilt the world or failed to move its original alias.");
        Check(workspace.CompiledObjects.GeneratedAssets.Select(asset => asset.TagHash).ToHashSet().SetEquals(generatedTags),
            "Changing a value reallocated generated identities.");
        workspace.Undo(); Wait(workspace);
        Check(project.ObjectEdits.Single().Scale == 3 && workspace.CanRedo, "Replacement edit undo failed.");
        Check(workspace.LastWorldRefresh is { Incremental: true } && ReferenceEquals(workspace.World, world)
            && selected.Transform.M11 == 3, "Isolated transform undo rebuilt the world or retained the new transform.");
        typeof(StudioWorkspace).GetProperty(nameof(StudioWorkspace.World))!.SetValue(workspace, null);
        Preview(catalog);
        workspace.Undo(); Wait(workspace);
        Check(project.ObjectEdits.Count == 0 && workspace.CompiledObjects.GeneratedAssets.Count == 0
            && catalog.GetOverlayEntries().All(entry => !entry.Generated)
            && generatedTags.All(tag => !catalog.ContainsTag(tag)), "Undo left private assets registered.");
        workspace.Redo(); Wait(workspace);
        Check(project.ObjectEdits.Single().Scale == 3, "Replacement redo lost the original edit.");
        Preview(catalog);
        string path = project.ManifestPath;
        workspace.CloseProject(); Wait(workspace);
        Check(generatedTags.All(tag => !catalog.ContainsTag(tag)), "Closing the project retained private assets.");
        workspace.OpenProject(path); Wait(workspace);
        Check(workspace.Project!.ObjectEdits.Single().Target == edit.Target
            && workspace.CompiledObjects.GeneratedAssets.Select(asset => asset.TagHash).ToHashSet().SetEquals(generatedTags),
            "Reopening changed the original target or private namespace.");
        Preview(catalog);
        Console.WriteLine("editor_isolation overlay=pass metadata=pass aliases=original edit=pass in_place=pass undo=pass redo=pass close=pass reopen=pass");
    }

    private static MeshInstance Preview(PackageCatalog catalog, StudioWorkspace? workspace = null)
    {
        var mesh = new MeshData { TagHash = StaticIsolationFixture.Mesh,
            Vertices = [new(Vector3.Zero, Vector3.UnitZ, Vector2.Zero, Vector4.One)], Indices = [] };
        var loader = new AssetSceneLoader(catalog)
        { MeshCache = new Dictionary<uint, MeshData[]> { [StaticIsolationFixture.Mesh] = [mesh] } };
        var scene = loader.LoadBubble(StaticIsolationFixture.Bubble);
        if (workspace is not null)
        {
            typeof(StudioWorkspace).GetProperty(nameof(StudioWorkspace.World))!.SetValue(workspace, WorldDocument.FromScene(scene));
            typeof(StudioWorkspace).GetField("worldChanges", System.Reflection.BindingFlags.Instance
                | System.Reflection.BindingFlags.NonPublic)!.SetValue(workspace, new HashSet<uint>());
        }
        Check(scene.Instances.Count == 3, "Workspace overlay duplicates or drops an instance.");
        var selected = scene.Instances.Single(instance => instance.InstanceSourceTag == StaticIsolationFixture.Table
            && instance.InstanceSourceIndex == 1);
        Check(selected.PlacementSourceTag == StaticIsolationFixture.List && selected.PlacementSourceOffset == 48,
            "Workspace overlay lost the original placement scope.");
        return selected;
    }

    private static void Wait(StudioWorkspace workspace)
    {
        var timer = Stopwatch.StartNew();
        while (workspace.IsBusy && timer.Elapsed < TimeSpan.FromSeconds(30))
        { workspace.Poll(); Thread.Sleep(1); }
        Check(!workspace.IsBusy && workspace.Error.Length == 0, workspace.Error);
    }

    private static void Check(bool valid, string message)
    { if (!valid) throw new InvalidOperationException(message); }
}
