using System.Globalization;
using System.Text;

namespace Solforge.Graphs;

public sealed record MissionCompileResult(string Lua, IReadOnlyList<string> Handlers, IReadOnlyList<GraphDiagnostic> Diagnostics);

/**
 * Compiles a mission graph to a Sunrise mission script module (the table of on_start, on_load and on_event_*
 * handlers MissionScriptFactory writes). Delay and Wait Signal continuations live in a per-run table keyed by the
 * state table; they do not survive a reload (on_load), which the generated header says.
 */
public static class MissionGraphCompiler
{
    private const string Header = """
        local sf = {}
        local runs = setmetatable({}, {__mode = "k"})
        local k = {}
        local signal_handlers = {}

        function sf.call(context, name, ...)
            local fn = context and context[name]
            if type(fn) ~= "function" then return nil end
            local ok, result = pcall(fn, context, ...)
            if ok then return result end
            print("[solforge] " .. name .. " failed: " .. tostring(result))
            return nil
        end

        function sf.run(state)
            local run = runs[state]
            if run == nil then
                run = {waiting = {}, timers = {}, once = {}, joins = {}, values = {}}
                runs[state] = run
            end
            return run
        end

        function sf.vars(state)
            state.sf_vars = state.sf_vars or {}
            return state.sf_vars
        end

        function sf.now(context, event)
            if type(event) == "table" and type(event.time) == "number" then return event.time end
            local now = sf.call(context, "get_time")
            if type(now) == "number" then return now end
            return os.clock()
        end

        function sf.filter_health(context, entity, threshold)
            if entity == nil then return nil end
            local health = sf.call(context, "get_health_fraction", entity)
            if type(health) == "number" and health < threshold then return entity end
            return nil
        end

        function sf.signal(context, state, event, name)
            local run = sf.run(state)
            local ready = {}
            for i = #run.waiting, 1, -1 do
                if run.waiting[i].signal == name then
                    table.insert(ready, 1, run.waiting[i].k)
                    table.remove(run.waiting, i)
                end
            end
            for _, handler in ipairs(signal_handlers[name] or {}) do handler(context, state, event) end
            for _, continuation in ipairs(ready) do continuation(context, state, event) end
        end

        function sf.tick(context, state, event)
            local run = sf.run(state)
            local now = sf.now(context, event)
            for i = #run.timers, 1, -1 do
                local timer = run.timers[i]
                if now >= timer.due then
                    table.remove(run.timers, i)
                    timer.k(context, state, event)
                end
            end
        end

        """;

    public static MissionCompileResult Compile(GraphDocument document)
    {
        var diagnostics = GraphValidation.Validate(document).ToList();
        var flat = GraphFlatten.Flatten(document);
        var writer = new Writer(flat, diagnostics);
        var lua = new StringBuilder();
        lua.Append("-- Generated by Solforge from mission graph \"").Append(document.Name.Replace("\n", " ")).AppendLine("\". Edit the graph, not this file.");
        lua.AppendLine("-- Delay and Wait Signal continuations are per run and are not restored by on_load.");
        lua.Append(Header);

        // Continuations first, so handlers can refer to them through k[...] in any order.
        foreach (var node in flat.Nodes.Where(node => node.Type is "flow.delay" or "flow.wait_signal" or "flow.parallel_all").OrderBy(node => node.Id, StringComparer.Ordinal))
        {
            string pin = node.Type switch { "flow.delay" => "completed", "flow.wait_signal" => "then", _ => "completed" };
            lua.Append("k[").Append(Quote(node.Id)).AppendLine("] = function(context, state, event)");
            writer.Chain(lua, node.Id, pin, 1, []);
            lua.AppendLine("end").AppendLine();
        }
        // On Signal handlers.
        foreach (var node in flat.OfType("mission.on_signal").OrderBy(node => node.Id, StringComparer.Ordinal))
        {
            string name = Quote(node.Get("signal", "ObjectiveUpdated"));
            lua.Append("signal_handlers[").Append(name).Append("] = signal_handlers[").Append(name).AppendLine("] or {}");
            lua.Append("table.insert(signal_handlers[").Append(name).AppendLine("], function(context, state, event)");
            writer.Chain(lua, node.Id, "then", 1, []);
            lua.AppendLine("end)").AppendLine();
        }
        // Activity callbacks.
        var handlers = new SortedDictionary<string, List<GraphNode>>(StringComparer.Ordinal);
        foreach (var node in flat.Nodes)
        {
            string? name = node.Type switch
            {
                "mission.start" => "on_start",
                "mission.event" => HandlerName(node.Get("event", "region_changed")),
                _ => null
            };
            if (name is null) continue;
            if (!handlers.TryGetValue(name, out var list)) handlers[name] = list = [];
            list.Add(node);
        }
        bool timers = flat.OfType("flow.delay").Any();
        if (timers && !handlers.ContainsKey("on_event_timer_elapsed")) handlers["on_event_timer_elapsed"] = [];
        lua.AppendLine("return {");
        foreach (var (name, nodes) in handlers)
        {
            lua.Append("    ").Append(name).AppendLine(" = function(context, state, event)");
            foreach (var node in nodes.OrderBy(node => node.Y).ThenBy(node => node.Id, StringComparer.Ordinal))
                writer.Chain(lua, node.Id, "then", 2, []);
            if (timers && name == "on_event_timer_elapsed") lua.AppendLine("        sf.tick(context, state, event)");
            lua.AppendLine("    end,");
        }
        lua.AppendLine("}");
        return new(lua.ToString(), [.. handlers.Keys], diagnostics);
    }

    private static string HandlerName(string callback) => callback is "on_start" or "on_load" ? callback : "on_event_" + callback;

    public static string Quote(string text)
    {
        var builder = new StringBuilder("\"");
        foreach (char c in text)
            builder.Append(c switch
            {
                '\\' => "\\\\", '"' => "\\\"", '\n' => "\\n", '\r' => "\\r", '\t' => "\\t",
                _ when c < ' ' => $"\\{(int)c:000}", _ => c.ToString()
            });
        return builder.Append('"').ToString();
    }

    private static string Number(double value) =>
        double.IsFinite(value) ? value.ToString("0.######", CultureInfo.InvariantCulture) : "0";

    private sealed class Writer(FlatGraph graph, List<GraphDiagnostic> diagnostics)
    {
        private const int MaxDepth = 64;

        /** Writes the statements reached from an exec output. */
        public void Chain(StringBuilder lua, string nodeId, string pin, int indent, HashSet<string> path)
        {
            foreach (var (node, _) in graph.Targets(nodeId, pin)) Statement(lua, node, indent, path);
        }

        private void Line(StringBuilder lua, int indent, string text) => lua.Append(' ', indent * 4).AppendLine(text);

        private void Statement(StringBuilder lua, GraphNode node, int indent, HashSet<string> path)
        {
            if (path.Contains(node.Id) || path.Count > MaxDepth)
            {
                Line(lua, indent, $"-- exec loop back to {node.Id} stopped");
                diagnostics.Add(new(DiagnosticSeverity.Warning, "Exec loop: use a signal or delay to repeat.", node.Id));
                return;
            }
            var next = new HashSet<string>(path, StringComparer.Ordinal) { node.Id };
            string id = Quote(node.Id);
            switch (node.Type)
            {
                case "flow.branch":
                    Line(lua, indent, $"if {Expr(node, "condition")} then");
                    Chain(lua, node.Id, "true", indent + 1, next);
                    if (graph.Targets(node.Id, "false").Any())
                    {
                        Line(lua, indent, "else");
                        Chain(lua, node.Id, "false", indent + 1, next);
                    }
                    Line(lua, indent, "end");
                    return;
                case "flow.sequence":
                    foreach (string then in new[] { "then0", "then1", "then2" }) Chain(lua, node.Id, then, indent, next);
                    return;
                case "flow.parallel_all":
                    Line(lua, indent, $"sf.run(state).joins[{id}] = 0");
                    Chain(lua, node.Id, "a", indent, next);
                    Chain(lua, node.Id, "b", indent, next);
                    return;
                case "flow.finish_branch":
                {
                    string parallel = Quote(node.Get("parallel"));
                    Line(lua, indent, "do");
                    Line(lua, indent + 1, "local joins = sf.run(state).joins");
                    Line(lua, indent + 1, $"joins[{parallel}] = (joins[{parallel}] or 0) + 1");
                    Line(lua, indent + 1, $"if joins[{parallel}] == 2 and k[{parallel}] then k[{parallel}](context, state, event) end");
                    Line(lua, indent, "end");
                    return;
                }
                case "flow.delay":
                    Line(lua, indent, $"table.insert(sf.run(state).timers, {{due = sf.now(context, event) + ({Expr(node, "seconds")}), k = k[{id}]}})");
                    return;
                case "flow.wait_signal":
                    Line(lua, indent, $"table.insert(sf.run(state).waiting, {{signal = {Quote(node.Get("signal", "ObjectiveUpdated"))}, k = k[{id}]}})");
                    return;
                case "flow.send_signal":
                    Line(lua, indent, $"sf.signal(context, state, event, {Quote(node.Get("signal", "ObjectiveUpdated"))})");
                    break;
                case "flow.do_once":
                    Line(lua, indent, $"if not sf.run(state).once[{id}] then");
                    Line(lua, indent + 1, $"sf.run(state).once[{id}] = true");
                    Chain(lua, node.Id, "then", indent + 1, next);
                    Line(lua, indent, "end");
                    return;
                case "state.set_flag":
                    Line(lua, indent, $"sf.vars(state)[{Quote(node.Get("name", "flag"))}] = {Expr(node, "value")} and true or false");
                    break;
                case "state.set_number":
                    Line(lua, indent, $"sf.vars(state)[{Quote(node.Get("name", "count"))}] = {Expr(node, "value")}");
                    break;
                case "mission.set_objective":
                    Line(lua, indent, $"sf.call(context, \"set_objective\", {Expr(node, "text")})");
                    break;
                case "mission.spawn_squad":
                    Line(lua, indent, $"sf.run(state).values[{Quote(node.Id + ".squad")}] = sf.call(context, \"spawn_squad\", {Quote(node.Get("name"))})");
                    break;
                case "mission.log":
                    Line(lua, indent, $"print(\"[mission] \" .. tostring({Expr(node, "text")}))");
                    break;
                case "mission.call":
                {
                    var args = new List<string>();
                    foreach (string arg in new[] { "a1", "a2", "a3" })
                        args.Add(graph.Sources(node.Id, arg).Any() || node.Properties.ContainsKey(arg) ? Expr(node, arg) : "nil");
                    while (args.Count > 0 && args[^1] == "nil") args.RemoveAt(args.Count - 1);
                    string call = $"sf.call(context, {Quote(node.Get("function"))}{string.Concat(args.Select(arg => ", " + arg))})";
                    Line(lua, indent, $"sf.run(state).values[{Quote(node.Id + ".result")}] = {call}");
                    break;
                }
                case "mission.lua":
                    Line(lua, indent, "do");
                    foreach (string text in node.Get("code").Replace("\r", "").Split('\n')) Line(lua, indent + 1, text);
                    Line(lua, indent, "end");
                    break;
                case NodeLibrary.Reroute:
                    Chain(lua, node.Id, "out", indent, next);
                    return;
                default:
                    Line(lua, indent, $"-- {node.Type} does not run in a mission graph");
                    diagnostics.Add(new(DiagnosticSeverity.Warning, $"{node.Type} does not run in a mission graph.", node.Id));
                    return;
            }
            Chain(lua, node.Id, "then", indent, next);
        }

        /** The Lua expression for an input pin's value. */
        private string Expr(GraphNode node, string pin, int depth = 0)
        {
            if (depth > MaxDepth) return "nil";
            foreach (var (source, sourcePin) in graph.Sources(node.Id, pin)) return Value(source, sourcePin, depth + 1);
            var definition = NodeLibrary.Find(node.Type)?.Pin(pin, false);
            string? text = node.Properties.TryGetValue(pin, out var typed) ? typed : definition?.Default;
            var type = definition is null || definition.Type == PinType.Any ? PinType.String : definition.Type;
            return Literal(GraphValue.Parse(type, text));
        }

        private static string Literal(GraphValue value) => value.Type switch
        {
            PinType.Bool => value.X != 0 ? "true" : "false",
            PinType.Int or PinType.Float or PinType.Numeric => Number(value.X),
            PinType.Vector2 => $"{{x = {Number(value.X)}, y = {Number(value.Y)}}}",
            PinType.Vector3 => $"{{x = {Number(value.X)}, y = {Number(value.Y)}, z = {Number(value.Z)}}}",
            PinType.Color => $"{{r = {Number(value.X)}, g = {Number(value.Y)}, b = {Number(value.Z)}, a = {Number(value.W)}}}",
            PinType.Entity => "nil",
            _ => Quote(value.Text ?? "")
        };

        private string Value(GraphNode node, string pin, int depth)
        {
            string In(string id) => Expr(node, id, depth);
            string Prop(string id) => node.Get(id, NodeLibrary.Find(node.Type)?.Property(id)?.Default ?? "");
            switch (node.Type)
            {
                case NodeLibrary.Reroute: return In("in");
                case "const.float": case "const.int": return Number(GraphValue.Parse(PinType.Float, Prop("value")).X);
                case "const.bool": return GraphValue.Parse(PinType.Bool, Prop("value")).X != 0 ? "true" : "false";
                case "const.string": return Quote(Prop("value"));
                case "const.vector3": return Literal(GraphValue.Parse(PinType.Vector3, Prop("value")));
                case "const.color": return Literal(GraphValue.Parse(PinType.Color, Prop("value")));
                case "math.add": return $"({In("a")} + {In("b")})";
                case "math.subtract": return $"({In("a")} - {In("b")})";
                case "math.multiply": return $"({In("a")} * {In("b")})";
                case "math.divide": return $"({In("a")} / {In("b")})";
                case "math.min": return $"math.min({In("a")}, {In("b")})";
                case "math.max": return $"math.max({In("a")}, {In("b")})";
                case "math.power": return $"({In("a")} ^ {In("b")})";
                case "math.one_minus": return $"(1 - {In("a")})";
                case "math.abs": return $"math.abs({In("a")})";
                case "math.negate": return $"(-{In("a")})";
                case "math.saturate": return $"math.max(0, math.min(1, {In("a")}))";
                case "math.floor": return $"math.floor({In("a")})";
                case "math.sqrt": return $"math.sqrt({In("a")})";
                case "math.lerp": return $"({In("a")} + ({In("b")} - {In("a")}) * {In("alpha")})";
                case "math.clamp": return $"math.max({In("min")}, math.min({In("max")}, {In("value")}))";
                case "logic.compare":
                    string op = Prop("op") switch { "!=" => "~=", "<=" or "==" or ">=" or ">" => Prop("op"), _ => "<" };
                    return $"({In("a")} {op} {In("b")})";
                case "logic.and": return $"({In("a")} and {In("b")})";
                case "logic.or": return $"({In("a")} or {In("b")})";
                case "logic.not": return $"(not {In("a")})";
                case "logic.select": return $"(function() if {In("condition")} then return {In("true")} end return {In("false")} end)()";
                case "vec.make3": return $"{{x = {In("x")}, y = {In("y")}, z = {In("z")}}}";
                case "vec.make_color": return $"{{r = {In("r")}, g = {In("g")}, b = {In("b")}, a = {In("a")}}}";
                case "vec.break":
                {
                    string[] names = pin switch { "x" => ["x", "r"], "y" => ["y", "g"], "z" => ["z", "b"], _ => ["w", "a"] };
                    return $"(function(v) return v.{names[0]} or v.{names[1]} end)({In("value")})";
                }
                case "state.get_flag": return $"(sf.vars(state)[{Quote(Prop("name"))}] == true)";
                case "state.get_number": return $"(sf.vars(state)[{Quote(Prop("name"))}] or 0)";
                case "event.field": return $"(({In("event")}) or {{}})[{Quote(Prop("field"))}]";
                case "mission.event": return "event";
                case "entity.get_player": return $"sf.call(context, \"get_player\", {In("index")})";
                case "entity.get_squad": return $"sf.call(context, \"get_squad\", {Quote(Prop("name"))})";
                case "entity.find_named_actor": return $"sf.call(context, \"find_named_actor\", {Quote(Prop("name"))})";
                case "entity.filter_by_health": return $"sf.filter_health(context, {In("entity")}, {In("threshold")})";
                case "mission.spawn_squad": return $"sf.run(state).values[{Quote(node.Id + ".squad")}]";
                case "mission.call": return $"sf.run(state).values[{Quote(node.Id + ".result")}]";
                case "conv.float_int": return $"math.floor({In("in")})";
                case "conv.bool_float": case "conv.bool_int": return $"({In("in")} and 1 or 0)";
                case "conv.int_string": case "conv.float_string": case "conv.bool_string": return $"tostring({In("in")})";
                case "conv.entity_bool": return $"({In("in")} ~= nil)";
            }
            if (node.Type.StartsWith("conv.", StringComparison.Ordinal)) return In("in");
            diagnostics.Add(new(DiagnosticSeverity.Warning, $"{node.Type} has no Lua value; nil is used.", node.Id));
            return "nil";
        }
    }
}
